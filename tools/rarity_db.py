#!/usr/bin/env python3
"""ProfessionBuddy rarity tool: the rarity of every item a recipe makes (2.2.2).

The recipe list's Sort: Rarity reads it. The game only knows an item's
rarity once it has loaded the item, so a live lookup leaves most of the
list without one; this tool bakes it from each game's own item table
(ItemSparse OverallQualityID: 0 Poor, 1 Common, 2 Uncommon, 3 Rare,
4 Epic, 5 Legendary):

  TBC Anniversary  Data/Rarity.lua, at the build Data/VendorPrices.lua
                   was baked from
  WoW: Forever     Data/Forever/Rarity.lua, at the recipe data's build

The items are the recipe-level itemID of every recipe in the data files
(not reagents). A recipe that makes no item (an enchant, itemID 0) has no
entry, and neither has an item missing from the game's item table.

  --check   does each file match the item table and the recipe data?
            Exits 0 = yes, 10 = run --regen --write.
  --regen   work both tables out; --write writes them.
  --csv DIR read ItemSparse_<build>.csv from DIR instead of wago.tools.

Usage:
  python tools/rarity_db.py --check [--addon-dir <path>]
  python tools/rarity_db.py --regen [--write] [--csv DIR]
"""
import argparse, csv, glob, io, os, re, sys, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bake_forever_db2 as F

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ADDON = os.path.normpath(os.path.join(HERE, "..", "ProfessionBuddy"))
# Anchors, so a broken join fails the bake: Linen Bandage is Common on
# both games; Embossed Leather Gloves is Common on TBC Anniversary and
# Uncommon on WoW: Forever; Primalstrike Vest is Epic (TBC Anniversary);
# Azure Gustwoven Belt is Uncommon (WoW: Forever).
ANCHORS = {False: {1251: 1, 4239: 1, 29525: 4},
           True: {1251: 1, 4239: 2, 277025: 2}}


def log(m): print(m, flush=True)


def tbc_build(addon_dir):
    """The TBC Anniversary build PB's vendor prices were baked from."""
    p = os.path.join(addon_dir, "Data", "VendorPrices.lua")
    m = re.search(r"build (\d+\.\d+\.\d+\.\d+)", open(p, encoding="utf-8").read())
    if not m:
        sys.exit("rarity_db: no TBC build stamp in " + p)
    return m.group(1)


def read_quality(build, csv_dir):
    p = csv_dir and os.path.join(csv_dir, "ItemSparse_%s.csv" % build)
    if p and os.path.isfile(p):
        rows = csv.DictReader(open(p, encoding="utf-8"))
    else:
        url = "https://wago.tools/db2/ItemSparse/csv?build=%s" % build
        log("  fetching ItemSparse for %s ..." % build)
        raw = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "pb"}), timeout=300).read()
        rows = csv.DictReader(io.StringIO(raw.decode("utf-8")))
    q = {}
    for r in rows:
        try:
            q[int(r["ID"])] = int(r["OverallQualityID"])
        except (KeyError, ValueError):
            continue
    return q


def crafted_ids(addon_dir, forever):
    """The recipe-level itemID of every recipe file (reagent rows start with
    a brace, so the line-start match skips them)."""
    d = os.path.join(addon_dir, "Data", "Forever") if forever else os.path.join(addon_dir, "Data")
    ids = set()
    for p in sorted(glob.glob(os.path.join(d, "*.lua"))):
        txt = open(p, encoding="utf-8").read()
        if "local recipes = {" not in txt:
            continue
        ids |= {int(x) for x in re.findall(r"(?m)^\s*itemID\s*=\s*(\d+),", txt)}
    ids.discard(0)
    return ids


def lua_file(forever, build, table, n_items):
    rel = "Data/Forever/Rarity.lua" if forever else "Data/Rarity.lua"
    lines = [
        "-- ProfessionBuddy  --  %s" % rel,
        "-- The rarity of every item a recipe makes (0 Poor .. 5 Legendary), for Sort: Rarity.",
        "-- Generated by tools/rarity_db.py from the game's item table, build %s" % build,
        "-- (ItemSparse OverallQualityID): %d of %d crafted items." % (len(table), n_items),
        "-- Do not edit by hand; regenerate.",
        "local addon = ProfBuddy",
        "addon.Rarity = {",
    ]
    for iid in sorted(table):
        lines.append("    [%d] = %d," % (iid, table[iid]))
    lines.append("}")
    return rel, "\n".join(lines) + "\n"


def plan(addon_dir, forever, build, csv_dir):
    q = read_quality(build, csv_dir)
    ids = crafted_ids(addon_dir, forever)
    table = {i: q[i] for i in ids if i in q}
    for iid, want in ANCHORS[forever].items():
        if table.get(iid) != want:
            sys.exit("rarity_db: anchor failed: item %d has rarity %s, expected %s" % (iid, table.get(iid), want))
    rel, txt = lua_file(forever, build, table, len(ids))
    return rel, txt, len(ids) - len(table)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--addon-dir", default=DEFAULT_ADDON)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--regen", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--csv")
    a = ap.parse_args()
    if not (a.check or a.regen):
        ap.print_help(); return
    builds = (("TBC Anniversary", False, tbc_build(a.addon_dir)),
              ("WoW: Forever", True, F.baked_build(os.path.join(a.addon_dir, "Data", "Forever"))))
    stale = 0
    for label, forever, build in builds:
        if not build:
            sys.exit("rarity_db: no %s build" % label)
        rel, txt, missing = plan(a.addon_dir, forever, build, a.csv)
        path = os.path.join(a.addon_dir, "Data", *rel.split("/")[1:])
        old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        same = old == txt
        log("%s (build %s): anchors OK, %d items with no rarity  |  %s %s"
            % (label, build, missing, rel, "up to date" if same else "differs"))
        if not same:
            stale += 1
            if a.regen and a.write:
                open(path, "w", encoding="utf-8", newline="\n").write(txt)
                log("  WROTE %s (%d bytes)" % (rel, len(txt)))
    if a.check:
        if stale:
            log("REBAKE: python tools/rarity_db.py --regen --write")
            sys.exit(10)
        log("UP TO DATE")
        sys.exit(0)


if __name__ == "__main__":
    main()
