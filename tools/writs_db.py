#!/usr/bin/env python3
"""ProfessionBuddy Craftsman's Writs tool (WoW: Forever).

What each Craftsman's Writ asks for, for the writ's tooltip ("Fill cost",
2.1.0 TEST-c). The game data names a writ's quest (ItemSparse
StartQuestID) but not what the quest asks for: that came from m4ru's
in-game harvest (ProfessionBuddyTester /pbt writs, 2026-11-08), kept here as
tools/forever/WRITS-harvest-2026-11-08.json (writ, quest, item, name,
count, reward, profession).

Writes Data/Forever/Writs.lua from the harvest.

  --check   compare the harvest with the game data of the Forever recipe
            data's build: every "Craftsman's Writ:" item with a quest is in
            the harvest with that quest, and nothing else is. Exits 0 = same,
            10 = a writ was added or changed (run /pbt writs again).
  --regen   write the file from the harvest (--write), checked first.

Usage:
  python tools/writs_db.py --check [--addon-dir <path>] [--csv DIR]
  python tools/writs_db.py --regen [--write]
"""
import argparse, csv, io, json, os, sys, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bake_forever_db2 as F

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ADDON = os.path.normpath(os.path.join(HERE, "..", "ProfessionBuddy"))
HARVEST = os.path.join(HERE, "forever", "WRITS-harvest-2026-11-08.json")
PREFIX = "Craftsman's Writ: "
# Writs older than WoW: Forever (the vanilla war-effort writs, 22568-22626)
# have no StartQuestID and are left out by that alone.


def log(m): print(m, flush=True)


def load_harvest():
    rows = json.load(open(HARVEST, encoding="utf-8"))
    out = {}
    for r in rows:
        w = int(r["writ"])
        if w in out: sys.exit("writs_db: writ %d twice in the harvest" % w)
        if int(r["count"]) < 1 or int(r["item"]) < 1: sys.exit("writs_db: writ %d has no item or count" % w)
        out[w] = r
    return out


def game_writs(build, csv_dir):
    if csv_dir:
        fh = open(os.path.join(csv_dir, "ItemSparse.csv"), encoding="utf-8", newline="")
        rows = list(csv.DictReader(fh))
    else:
        url = "https://wago.tools/db2/ItemSparse/csv?build=%s" % build
        req = urllib.request.Request(url, headers={"User-Agent": "ProfessionBuddy-bake"})
        rows = list(csv.DictReader(io.StringIO(urllib.request.urlopen(req, timeout=300).read().decode("utf-8"))))
    return {int(r["ID"]): int(r["StartQuestID"] or 0) for r in rows
            if (r.get("Display_lang") or "").startswith(PREFIX) and int(r.get("StartQuestID") or 0) > 0}


def compare(harvest, game):
    diffs = []
    for w, q in sorted(game.items()):
        h = harvest.get(w)
        if not h: diffs.append("writ %d (quest %d) is in the game, not in the harvest" % (w, q))
        elif int(h["quest"]) != q: diffs.append("writ %d: quest %d in the game, %s in the harvest" % (w, q, h["quest"]))
    for w in sorted(set(harvest) - set(game)):
        diffs.append("writ %d is in the harvest, not in the game" % w)
    return diffs


def render(harvest, build):
    lines = [
        "-- ProfessionBuddy  --  Data/Forever/Writs.lua",
        "-- What each Craftsman's Writ asks for: the item and count its quest wants.",
        "-- For the writ's tooltip (Fill cost, UI/TradeSkillFrame.lua). WoW: Forever only.",
        "-- Generated by tools/writs_db.py from m4ru's /pbt writs harvest (2026-11-08),",
        "-- checked against the game's writs, build %s. Do not edit by hand." % build,
        "local addon = ProfBuddy",
        "-- [writ] = { item, count, quest }",
        "addon.Writs = {",
    ]
    for w in sorted(harvest):
        r = harvest[w]
        lines.append("    [%d] = { %d, %d, %d },   -- %s x %d (%s)" % (
            w, int(r["item"]), int(r["count"]), int(r["quest"]), r["name"], int(r["count"]), r["prof"]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--addon-dir", default=DEFAULT_ADDON)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--regen", action="store_true")
    ap.add_argument("--csv")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    build = F.baked_build(os.path.join(a.addon_dir, "Data", "Forever"))
    harvest = load_harvest()
    if a.check or a.regen:
        diffs = compare(harvest, game_writs(build, a.csv))
        log("Craftsman's Writs: %d in the harvest, game build %s" % (len(harvest), build))
        for d in diffs: log("  " + d)
        if diffs:
            log("CHANGED: run /pbt writs again and replace the harvest")
            sys.exit(10)
        log("UP TO DATE")
        if a.check: sys.exit(0)
    if a.regen:
        text = render(harvest, build)
        p = os.path.join(a.addon_dir, "Data", "Forever", "Writs.lua")
        if a.write:
            with open(p, "w", encoding="utf-8", newline="\n") as fh: fh.write(text)
            log("wrote " + p)
        else:
            sys.stdout.write(text[:1200])
        return
    ap.print_help()


if __name__ == "__main__":
    main()
