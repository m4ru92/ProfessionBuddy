-- final say. A wrong value gets fixed from a player's report (m4ru's
-- call, 2026-10-02).
--
-- NODE LOOT (Phase 3b-4): NodeItems, NodeLootTables and NodeLoot (node
-- name -> table index), from the same VMaNGOS build: for each node name
-- above, the loot of its most-spawned game object entry.
